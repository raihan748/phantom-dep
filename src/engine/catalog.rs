use crate::model::Ecosystem;

/// Returns true if the package is in the verified popular catalog for the ecosystem
pub fn is_in_popular_catalog(ecosystem: Ecosystem, name: &str) -> bool {
    let lower = name.to_ascii_lowercase();
    let catalog = get_catalog(ecosystem);
    catalog.iter().any(|&item| item.eq_ignore_ascii_case(&lower))
}

/// Returns true if the name matches a standard library module in that ecosystem
pub fn is_standard_library(ecosystem: Ecosystem, name: &str) -> bool {
    let lower = name.to_ascii_lowercase();
    let std_libs = get_standard_libraries(ecosystem);
    std_libs.iter().any(|&item| item.eq_ignore_ascii_case(&lower))
}

/// Retrieves list of popular packages for an ecosystem
pub fn get_catalog(ecosystem: Ecosystem) -> &'static [&'static str] {
    match ecosystem {
        Ecosystem::Npm => NPM_CATALOG,
        Ecosystem::PyPi => PYPI_CATALOG,
        Ecosystem::Cargo => CARGO_CATALOG,
        Ecosystem::Go => GO_CATALOG,
    }
}

/// Retrieves standard library modules for an ecosystem
pub fn get_standard_libraries(ecosystem: Ecosystem) -> &'static [&'static str] {
    match ecosystem {
        Ecosystem::Npm => NODE_STDLIB,
        Ecosystem::PyPi => PYTHON_STDLIB,
        Ecosystem::Cargo => RUST_STDLIB,
        Ecosystem::Go => GO_STDLIB,
    }
}

